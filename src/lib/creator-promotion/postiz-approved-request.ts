function block(message: string): never {
  throw new PostizScheduleBlockedError(message);
}

function unsafeHost(hostname: string): boolean {
  const host = hostname.toLowerCase().replace(/^\[|\]$/g, "");
  return (
    host === "localhost" ||
    host.endsWith(".localhost") ||
    host.endsWith(".local") ||
    host === "::1" ||
    host === "0.0.0.0" ||
    /^127\./.test(host) ||
    /^10\./.test(host) ||
    /^192\.168\./.test(host) ||
    /^169\.254\./.test(host) ||
    /^0\./.test(host) ||
    /^172\.(?:1[6-9]|2\d|3[01])\./.test(host) ||
    /^fc[0-9a-f]{2}:/i.test(host) ||
    /^fd[0-9a-f]{2}:/i.test(host) ||
    /^fe80:/i.test(host)
  );
}

/**
 * A Postiz endpoint must be a clean public HTTPS origin. Credentials, paths,
 * query strings, and fragments would make a deployment secret ambiguous.
 */
export function cleanPostizOrigin(value: string): string {
  let url: URL;
  try {
    url = new URL(value);
  } catch {
    block("Postiz URL is invalid");
  }
  if (
    url.protocol !== "https:" ||
    url.username ||
    url.password ||
    url.search ||
    url.hash ||
    (url.pathname !== "" && url.pathname !== "/") ||
    unsafeHost(url.hostname)
  ) {
    block("Postiz URL must be a clean public HTTPS origin");
  }
  return url.origin;
}

/**
 * The only source URL passed to Postiz is generated by the Media Engine worker
 * for a controlled R2 object. Query parameters are permitted because an R2
 * signed URL needs them; credentials, fragments, private hosts, and non-HTTPS
 * origins are not.
 */
export function validatePostizUploadSourceUrl(value: string): string {
  let url: URL;
  try {
    url = new URL(value);
  } catch {
    block("approved Postiz media URL is invalid");
  }
  if (
    url.protocol !== "https:" ||
    url.username ||
    url.password ||
    url.hash ||
    unsafeHost(url.hostname)
  ) {
    block("approved Postiz media URL is unsafe");
  }
  return url.toString();
}

function validatePostizUploadedAssetUrl(value: string): string {
  let url: URL;
  try {
    url = new URL(value);
  } catch {
    block("Postiz returned an invalid uploaded media path");
  }
  if (
    url.protocol !== "https:" ||
    url.username ||
    url.password ||
    url.search ||
    url.hash ||
    unsafeHost(url.hostname)
  ) {
    block("Postiz returned an unsafe uploaded media path");
  }
  return url.toString();
}

