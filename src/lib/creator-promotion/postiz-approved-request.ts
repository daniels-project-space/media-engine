/**
 * Time is deliberately checked at the provider side-effect boundary rather
 * than while parsing the immutable snapshot. A completed action can therefore
 * be safely recognized as completed on a later Trigger replay, while a fresh
 * request that has become near-due still cannot be sent to Postiz.
 */
export function assertPostizScheduleIsSafelyFuture(
  input: PostizApprovedSchedule,
): PostizApprovedSchedule {
  const action = PostizApprovedScheduleSchema.parse(input);
  if (action.scheduledAt < Date.now() + POSTIZ_MINIMUM_SCHEDULE_LEAD_TIME_MS) {
    block("Postiz schedule time must be at least one minute in the future");
  }
  return action;
}

